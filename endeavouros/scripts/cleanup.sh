#!/usr/bin/env bash
# Final cleanup before the disk is packaged (runs as root, every provider).
set -euxo pipefail

pacman -Scc --noconfirm
rm -rf /var/lib/pacman/sync/*

# Exactly one systemd-networkd file.
test "$(ls /etc/systemd/network)" = 99-hako-ethernet.network

# Every VM gets its own pacman master key: hako-pacman-init.service creates
# it on first boot while the trust database is missing (see the unit, as in
# the Arch box). Ship only the public keys of every installed keyring
# (Arch or Arch Linux ARM, and EndeavourOS), imported now because importing
# them is the slow part; pubring.gpg must exist first, as pacman uses
# GnuPG's legacy keyring format.
keyrings=/usr/local/share/hako/pacman-keyrings   # populate source, see the unit
rm -rf "$keyrings"
install -d -m 0755 "$keyrings"
keyring=/etc/pacman.d/gnupg
gpgconf --homedir "$keyring" --kill all 2>/dev/null || true
rm -rf "$keyring"
install -d -m 0755 "$keyring"
touch "$keyring/pubring.gpg"
for gpgfile in /usr/share/pacman/keyrings/*.gpg; do
  name=$(basename "$gpgfile" .gpg)
  gpg --homedir "$keyring" --no-permission-warning --quiet --import "$gpgfile" 2>/dev/null || true
  : > "$keyrings/$name.gpg"
  for list in trusted revoked; do
    [ ! -e "/usr/share/pacman/keyrings/$name-$list" ] ||
      ln -sf "/usr/share/pacman/keyrings/$name-$list" "$keyrings/$name-$list"
  done
done
ls -l "$keyrings"
test "$(gpg --homedir "$keyring" --no-permission-warning --list-keys --with-colons | grep -c '^pub')" -gt 10
gpgconf --homedir "$keyring" --kill all 2>/dev/null || true
find "$keyring" -mindepth 1 ! -name pubring.gpg -delete

# New machine-id (and DHCP client id) on first boot of every VM.
truncate -s 0 /etc/machine-id
rm -f /var/lib/systemd/random-seed
rm -rf /var/lib/systemd/network/*

# Per-VM SSH host keys (regenerated by hako-ssh-hostkeys.service).
rm -f /etc/ssh/ssh_host_*

# Logs, temp files, shell history.
journalctl --rotate || true
journalctl --vacuum-time=1s || true
find /var/log -type f -exec truncate -s 0 {} +
rm -rf /tmp/* /var/tmp/*
rm -f /root/.bash_history /home/vagrant/.bash_history

# Hand free blocks back to the hypervisor so the image compacts well.
# QEMU (discard=unmap) honours TRIM. VirtualBox ignores TRIM on VMDK disks,
# so there the free space is zero-filled.
if [ "${HAKO_PROVIDER:-}" = virtualbox ]; then
  for fs in / /boot; do
    dd if=/dev/zero of="$fs/ZERO" bs=4M status=none || true
    sync
    rm -f "$fs/ZERO"
  done
fi
fstrim -av || true
sync
