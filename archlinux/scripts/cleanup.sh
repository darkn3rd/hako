#!/usr/bin/env bash
# Final cleanup before the disk is packaged (runs as root, every provider).
set -euxo pipefail

# Drop orphaned packages and the package cache.
orphans=$(pacman -Qdtq || true)
[[ -z $orphans ]] || pacman -Rns --noconfirm $orphans
pacman -Scc --noconfirm

# Reset cloud-init so a VM made from the box is a new instance; drop the
# build seed and logs, and the network file the build seed generated.
cloud-init clean --logs --seed
rm -f /etc/systemd/network/10-cloud-init-*.network

# Exactly one systemd-networkd file must remain.
ls -l /etc/systemd/network
test "$(ls /etc/systemd/network/*.network | wc -l)" -eq 1

# Every VM gets its own pacman master key: hako-pacman-init.service creates
# it on first boot while the trust database is missing. Ship only the public
# packager keys, imported now because importing them is the slow part of
# first boot (see the unit). pubring.gpg must exist first: pacman uses GnuPG's
# legacy keyring format, not the default keybox.
systemctl is-enabled hako-pacman-init.service
keyring=/etc/pacman.d/gnupg
gpgconf --homedir "$keyring" --kill all 2>/dev/null || true
rm -rf "$keyring"
install -d -m 0755 "$keyring"
touch "$keyring/pubring.gpg"
gpg --homedir "$keyring" --no-permission-warning --quiet --import /usr/share/pacman/keyrings/archlinux.gpg 2>/dev/null || true
test "$(gpg --homedir "$keyring" --no-permission-warning --list-keys --with-colons | grep -c '^pub')" -gt 10
gpgconf --homedir "$keyring" --kill all 2>/dev/null || true
find "$keyring" -mindepth 1 ! -name pubring.gpg -delete
ls -l "$keyring"

# New machine-id (and DHCP DUID) on first boot of every VM.
truncate -s 0 /etc/machine-id
rm -f /var/lib/dbus/machine-id
rm -f /var/lib/systemd/random-seed

# Per-VM SSH host keys (regenerated by hako-ssh-hostkeys.service).
rm -f /etc/ssh/ssh_host_*

# Logs, caches, temp files, shell history.
journalctl --rotate || true
journalctl --vacuum-time=1s || true
find /var/log -type f -exec truncate -s 0 {} +
rm -rf /tmp/* /var/tmp/*
rm -f /root/.bash_history /home/vagrant/.bash_history
rm -rf /var/lib/systemd/network/* 2>/dev/null || true

# Hand free blocks back to the hypervisor so the image compacts well.
# QEMU (discard=unmap) honours TRIM. VirtualBox ignores TRIM on VMDK disks,
# so there the free space is zero-filled. The root filesystem is btrfs, which
# compresses zeros away, so zero-fill with compression off for that file.
if pacman -Q virtualbox-guest-utils-nox >/dev/null 2>&1; then
  for fs in / /boot /efi; do
    mountpoint -q "$fs" || [[ $fs == / ]] || continue
    touch "$fs/ZERO"; chattr +C "$fs/ZERO" 2>/dev/null || true
    btrfs property set "$fs/ZERO" compression none 2>/dev/null || true
    dd if=/dev/zero of="$fs/ZERO" bs=4M status=none || true
    sync
    rm -f "$fs/ZERO"
  done
fi
fstrim -av || true
sync
