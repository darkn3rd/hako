#!/usr/bin/env bash
# Final cleanup before the disk is packaged (runs as root, every provider).
set -euxo pipefail
export DEBIAN_FRONTEND=noninteractive
export NEEDRESTART_SUSPEND=1

apt-get -y autoremove --purge
apt-get clean
rm -rf /var/lib/apt/lists/*

# Reset cloud-init so a VM made from the box is a new instance; drop the
# build seed and logs.
cloud-init clean --logs --seed
rm -f /etc/netplan/50-cloud-init.yaml
rm -f /etc/cloud/cloud.cfg.d/50-curtin-networking.cfg /etc/cloud/cloud.cfg.d/90-installer-network.cfg

# Exactly one netplan file must remain.
ls -l /etc/netplan
test "$(ls /etc/netplan | wc -l)" -eq 1

# New machine-id (and DHCP DUID) on first boot of every VM.
truncate -s 0 /etc/machine-id
rm -f /var/lib/dbus/machine-id
ln -s /etc/machine-id /var/lib/dbus/machine-id
rm -f /var/lib/systemd/random-seed

# Per-VM SSH host keys (regenerated by hako-ssh-hostkeys.service).
rm -f /etc/ssh/ssh_host_*

# Logs, caches, temp files, shell history.
journalctl --rotate || true
journalctl --vacuum-time=1s || true
find /var/log -type f -exec truncate -s 0 {} +
rm -rf /tmp/* /var/tmp/* /var/cache/apt/archives/*.deb
rm -f /root/.bash_history /home/vagrant/.bash_history
rm -rf /var/lib/dhcp/* /var/lib/systemd/network/* 2>/dev/null || true

# Hand free blocks back to the hypervisor so the image compacts well.
fstrim -av || true
sync
